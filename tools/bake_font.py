"""Bakes the monogram pixel font (CC0, datagoblin) into src/render/Font.gen.h for
the menus: one row of bits per glyph line, printable ASCII.

Run: python tools/bake_font.py <monogram.ttf>
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

WIDTH = 6   # each glyph's advance, bit 5 the leftmost pixel
HEIGHT = 10  # cap height 7, two rows of descender, one blank
TOP = 4      # the rows above the cap line at size 16


def main():
    ttf = Path(sys.argv[1] if len(sys.argv) > 1 else r"C:\dkt\pocket-dungeon-art\raw\monogram.ttf")
    out = Path(__file__).resolve().parent.parent / "src" / "render" / "Font.gen.h"
    font = ImageFont.truetype(str(ttf), 16)
    rows = []
    for code in range(32, 127):
        image = Image.new("L", (WIDTH + 4, HEIGHT + TOP + 4), 0)
        ImageDraw.Draw(image).text((0, 0), chr(code), font=font, fill=255)
        glyph = []
        for y in range(HEIGHT):
            bits = 0
            for x in range(WIDTH):
                if image.getpixel((x, y + TOP)) > 127:
                    bits |= 1 << (WIDTH - 1 - x)
            glyph.append(bits)
        rows.append((code, glyph))
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/bake_font.py from monogram (CC0, datagoblin) - do not edit.",
        f"// {WIDTH}x{HEIGHT} pixel glyphs for ASCII 32-126, one byte per line, bit {WIDTH - 1} leftmost.",
        "",
        "#include <cstdint>",
        "",
        "namespace Dungeon::Font",
        "{",
        "",
        f"constexpr int kWidth = {WIDTH};",
        f"constexpr int kHeight = {HEIGHT};",
        "constexpr int kFirst = 32;",
        "constexpr int kLast = 126;",
        "",
        "inline constexpr uint8_t kGlyphs[][kHeight] = {",
    ]
    for code, glyph in rows:
        shown = chr(code) if chr(code) not in "\\" else "backslash"
        lines.append("    { " + ", ".join(f"0x{b:02X}" for b in glyph) + " },  // " + shown)
    lines += ["};", "", "}  // namespace Dungeon::Font", ""]
    out.write_text("\n".join(lines), newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()

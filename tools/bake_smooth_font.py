"""Bakes JetBrains Mono (OFL) into src/render/SmoothFont.gen.h: smooth text for the
HUD and menus, at two sizes, one byte of coverage per pixel (0 to 3), so the
text blends into whatever is behind it.

Run: python tools/bake_smooth_font.py <JetBrainsMono-Regular.ttf>
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# name, pixel size
FACES = [("Small", 12), ("Large", 18)]


def main():
    ttf = Path(sys.argv[1] if len(sys.argv) > 1 else r"C:\dkt\pocket-dungeon-art\raw\JetBrainsMono-Regular.ttf")
    out = Path(__file__).resolve().parent.parent / "src" / "render" / "SmoothFont.gen.h"
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/bake_smooth_font.py from JetBrains Mono (SIL OFL 1.1) - do not edit.",
        "// Each face: printable ASCII, every glyph `width` x `height`, one coverage value",
        "// per pixel from 0 (none) to 3 (full), row by row.",
        "",
        "#include <cstdint>",
        "",
        "namespace Dungeon::SmoothFont",
        "{",
        "",
        "struct Face",
        "{",
        "    int width;",
        "    int height;",
        "    const uint8_t* coverage;  // (126 - 32 + 1) glyphs",
        "};",
        "",
        "constexpr int kFirst = 32;",
        "constexpr int kLast = 126;",
        "",
    ]
    for name, size in FACES:
        font = ImageFont.truetype(str(ttf), size)
        ascent, descent = font.getmetrics()
        width = int(round(font.getlength("M")))
        height = ascent + descent
        values = []
        for code in range(32, 127):
            image = Image.new("L", (width, height), 0)
            ImageDraw.Draw(image).text((0, 0), chr(code), font=font, fill=255)
            for v in image.getdata():
                values.append(min(3, (v + 42) // 85))
        lines.append(f"inline constexpr uint8_t k{name}Coverage[] = {{")
        for i in range(0, len(values), 48):
            lines.append("    " + ",".join(str(v) for v in values[i:i + 48]) + ",")
        lines.append("};")
        lines.append(f"inline constexpr Face k{name}{{ {width}, {height}, k{name}Coverage }};")
        lines.append("")
        print(f"{name}: {width}x{height}, {len(values)} bytes")
    lines += ["}  // namespace Dungeon::SmoothFont", ""]
    out.write_text("\n".join(lines), newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
